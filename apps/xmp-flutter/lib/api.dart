import 'dart:async';
import 'dart:math';
import 'models.dart';
import 'src/rust/frb_generated.dart/api.dart' as rust;

abstract class XmpApi {
  Future<Map<String, dynamic>> connect(Map<String, dynamic> args);
  Future<void> logout();
  Future<List<Friend>> friends();
  Future<void> friendRequest(String username);
  Future<void> friendAccept(int userId);
  Future<List<Conv>> conversations();
  Future<List<Msg>> sync(int conv, int after);
  Future<Map<String, dynamic>> sendText(int to, String text);
  Future<void> sendFile(int to, String path);
  Future<void> downloadFile(String hash, int size, String dest);
  Future<Map<String, dynamic>> callStart(int peer, bool video);
  Future<Map<String, dynamic>> callAccept(String callId, int peer, bool video);
  Future<void> callReject(String callId, int peer);
  Future<void> callHangup();
  Future<Map<String, dynamic>> callStats();

  Stream<Map<String, dynamic>> get onEvent;
}

class RustApi implements XmpApi {
  final _eventController = StreamController<Map<String, dynamic>>.broadcast();

  @override
  Stream<Map<String, dynamic>> get onEvent => _eventController.stream;

  @override
  Future<Map<String, dynamic>> connect(Map<String, dynamic> args) async {
    // 1. Establish the event stream first
    // Note: createEventStream is generated by FRB v2 from a function taking StreamSink
    rust.createEventStream().listen((event) {
      _eventController.add(_mapRustEvent(event));
    });

    // 2. Call connect to get user info
    final me = await rust.connect(
      server: args['server'],
      serverName: args['server_name'],
      certB64: args['cert_b64'],
      mode: args['mode'],
      username: args['username'],
      password: args['password'],
      token: args['token'],
    );
    return {'user_id': me.userId.toInt(), 'token': me.token};
  }

  Map<String, dynamic> _mapRustEvent(rust.XmpEvent event) {
    // This maps FRB generated XmpEvent to the Map format used by XmpStore
    return event.map(
      message: (e) => {
        'type': 'message',
        'message': {
          'conv': e.message.conv.toInt(),
          'seq': e.message.seq.toInt(),
          'sender': e.message.sender.toInt(),
          'kind': e.message.kind,
          'ts': e.message.ts.toInt(),
          'text': e.message.text,
        }
      },
      presence: (e) => {
        'type': 'presence',
        'user': e.user.toInt(),
        'online': e.online,
      },
      incomingCall: (e) => {
        'type': 'incoming_call',
        'call_id': e.callId,
        'peer': e.peer.toInt(),
        'video': e.video,
      },
      callEnded: (e) => {
        'type': 'call_ended',
        'call_id': e.callId,
        'peer': e.peer.toInt(),
      },
      disconnected: (e) => {'type': 'disconnected'},
    );
  }

  @override
  Future<void> logout() => rust.logout();

  @override
  Future<List<Friend>> friends() async {
    final fs = await rust.getFriends();
    return fs
        .map((f) => Friend(
              id: f.id,
              username: f.username,
              displayName: f.displayName,
              status: _parseStatus(f.status),
            ))
        .toList();
  }

  static FriendStatus _parseStatus(String status) {
    switch (status) {
      case 'sent':
        return FriendStatus.sent;
      case 'received':
        return FriendStatus.received;
      case 'friends':
        return FriendStatus.friends;
      default:
        return FriendStatus.friends;
    }
  }

  @override
  Future<Map<String, dynamic>> sendText(int to, String text) async {
    final res = await rust.sendText(to: to, text: text);
    return {
      'conv': res.conv,
      'seq': res.lastSeq,
      'ts': DateTime.now().millisecondsSinceEpoch,
    };
  }

  @override
  Future<void> friendRequest(String username) =>
      rust.friendRequest(username: username);

  @override
  Future<void> friendAccept(int userId) =>
      rust.friendAccept(userId: userId);

  @override
  Future<List<Conv>> conversations() async =>
      (await rust.getConversations()).map((c) => Conv(
            conv: c.conv.toInt(),
            peer: c.peer.toInt(),
            lastSeq: c.lastSeq.toInt(),
          )).toList();

  @override
  Future<List<Msg>> sync(int conv, int after) async =>
      (await rust.syncMessages(conv: conv, after: after)).map(_msg).toList();

  @override
  Future<void> sendFile(int to, String path) async {
    await rust.sendFile(to: to, path: path);
  }

  @override
  Future<void> downloadFile(String hash, int size, String dest) async {
    await rust.downloadFile(
        hash: hash, size: BigInt.from(size), name: 'download', dest: dest);
  }

  @override
  Future<Map<String, dynamic>> callStart(int peer, bool video) async {
    final c = await rust.callStart(peer: peer, video: video);
    return {'call_id': c.callId, 'peer': c.peer.toInt(), 'video': c.video, 'sas': c.sas};
  }

  @override
  Future<Map<String, dynamic>> callAccept(
          String callId, int peer, bool video) async {
    final c = await rust.callAccept(callId: callId, peer: peer, video: video);
    return {'call_id': c.callId, 'peer': c.peer.toInt(), 'video': c.video, 'sas': c.sas};
  }

  @override
  Future<void> callReject(String callId, int peer) =>
      rust.callReject(callId: callId, peer: peer);

  @override
  Future<void> callHangup() => rust.callHangup();

  @override
  Future<Map<String, dynamic>> callStats() async {
    final s = await rust.callStats();
    return {
      'path': s.path,
      'video_target_kbps': s.videoTargetKbps,
      'tx': s.tx,
      'rx': s.rx,
      'retransmits': s.retransmits,
      'fec_recovered': s.fecRecovered,
    };
  }

  static Msg _msg(rust.MsgDto m) => Msg(
        conv: m.conv.toInt(),
        seq: m.seq.toInt(),
        sender: m.sender.toInt(),
        kind: m.kind,
        ts: m.ts.toInt(),
        text: m.text,
        file: m.file == null
            ? null
            : FileRef(name: m.file!.name, size: m.file!.size.toInt(), hash: m.file!.hash),
      );
}

